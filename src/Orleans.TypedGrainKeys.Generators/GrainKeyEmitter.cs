using System.Linq;
using System.Text;

namespace Orleans.TypedGrainKeys.Generators;

internal static class GrainKeyEmitter
{
    public static string Emit(KeyModel key)
    {
        var t = key.FullyQualifiedName;
        var declaration = key.IsValueType
            ? (key.IsReadOnly ? "readonly partial record struct" : "partial record struct")
            : "partial record";

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        if (key.Namespace is not null)
        {
            sb.AppendLine($"namespace {key.Namespace};");
            sb.AppendLine();
        }

        sb.AppendLine($"{declaration} {key.Name} : global::Orleans.ITypedGrainKey<{t}>, global::System.IParsable<{t}>");
        sb.AppendLine("{");

        // Conversions used by Orleans' string key APIs.
        sb.AppendLine("    /// <summary>Encodes the key as an Orleans grain key string.</summary>");
        sb.AppendLine($"    public static implicit operator string({t} key)");
        sb.AppendLine("    {");
        sb.AppendLine("        var writer = global::Orleans.TypedGrainKeyWriter.Create();");
        sb.AppendLine("        WriteGrainKeyParts(writer, key);");
        sb.AppendLine("        return writer.Build();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Decodes an Orleans grain key string.</summary>");
        sb.AppendLine("    /// <exception cref=\"global::Orleans.GrainKeyFormatException\">The key is not a valid encoded key of this type.</exception>");
        sb.AppendLine($"    public static implicit operator {t}(string key) => Parse(key);");
        sb.AppendLine();

        // Parse / TryParse, also implementing IParsable<T>.
        sb.AppendLine("    /// <summary>Decodes an Orleans grain key string.</summary>");
        sb.AppendLine("    /// <exception cref=\"global::Orleans.GrainKeyFormatException\">The key is not a valid encoded key of this type.</exception>");
        sb.AppendLine($"    public static {t} Parse(string key)");
        sb.AppendLine("    {");
        sb.AppendLine($"        using var reader = global::Orleans.TypedGrainKeyReader.Create<{t}>(key);");
        sb.AppendLine("        return ReadGrainKeyParts(reader);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    public static {t} Parse(string s, global::System.IFormatProvider? provider) => Parse(s);");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Tries to decode an Orleans grain key string.</summary>");
        sb.AppendLine($"    public static bool TryParse([global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] string? key, [global::System.Diagnostics.CodeAnalysis.MaybeNullWhen(false)] out {t} result)");
        sb.AppendLine($"        => global::Orleans.TypedGrainKey.TryParse<{t}>(key, out result);");
        sb.AppendLine();
        sb.AppendLine($"    public static bool TryParse([global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] string? s, global::System.IFormatProvider? provider, [global::System.Diagnostics.CodeAnalysis.MaybeNullWhen(false)] out {t} result)");
        sb.AppendLine("        => TryParse(s, out result);");
        sb.AppendLine();

        // Part writers/readers. Public so keys in other assemblies can nest this key.
        sb.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        sb.AppendLine($"    public static void WriteGrainKeyParts(global::Orleans.TypedGrainKeyWriter writer, {t} key)");
        sb.AppendLine("    {");
        if (!key.IsValueType)
        {
            sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(key);");
        }

        foreach (var part in key.Parts)
        {
            sb.AppendLine($"        {WriteStatement(part)}");
        }

        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        sb.AppendLine($"    public static {t} ReadGrainKeyParts(global::Orleans.TypedGrainKeyReader reader)");
        sb.AppendLine("    {");

        // Read into locals first so the read order is explicit and matches the write order.
        var index = 0;
        foreach (var part in key.Parts)
        {
            sb.AppendLine($"        var part{index++} = {ReadExpression(part)};");
        }

        var arguments = string.Join(", ", Enumerable.Range(0, key.Parts.Count).Select(i => $"part{i}"));
        sb.AppendLine($"        return new {t}({arguments});");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private static string WriteStatement(PartModel part) => part.Kind switch
    {
        PartKind.Enum => $"writer.Write<{part.TypeName}>(key.{part.MemberName});",
        PartKind.Nested => $"{part.TypeName}.WriteGrainKeyParts(writer, key.{part.MemberName});",
        _ => $"writer.Write(key.{part.MemberName});"
    };

    private static string ReadExpression(PartModel part) => part.Kind switch
    {
        PartKind.String => "reader.ReadString()",
        PartKind.Guid => "reader.ReadGuid()",
        PartKind.Int32 => "reader.ReadInt32()",
        PartKind.Int64 => "reader.ReadInt64()",
        PartKind.Boolean => "reader.ReadBoolean()",
        PartKind.DateTime => "reader.ReadDateTime()",
        PartKind.DateTimeOffset => "reader.ReadDateTimeOffset()",
        PartKind.DateOnly => "reader.ReadDateOnly()",
        PartKind.TimeOnly => "reader.ReadTimeOnly()",
        PartKind.TimeSpan => "reader.ReadTimeSpan()",
        PartKind.Enum => $"reader.ReadEnum<{part.TypeName}>()",
        PartKind.Nested => $"{part.TypeName}.ReadGrainKeyParts(reader)",
        _ => throw new System.ArgumentOutOfRangeException(nameof(part))
    };
}
